def board_of(code):
    if code.startswith("60"): return "沪市主板"
    if code.startswith("30"): return "创业板"
    if code.startswith("68"): return "科创板"
    return "深市主板"

def main():
    conn = sqlite3.connect(DB_PATH, timeout=15)
    conn.execute("PRAGMA busy_timeout=15000")
    cur = conn.cursor()
    # 幂等键 = 本脚本固定 created_at 常量(pattern_type 是结构化标签,不能做幂等键)
    cur.execute("SELECT COUNT(*) FROM limit_up_patterns WHERE trade_date=? AND created_at=?", (TRADE_DATE, NOW))
    pre = cur.fetchone()[0]
    cur.execute("DELETE FROM limit_up_patterns WHERE trade_date=? AND created_at=?", (TRADE_DATE, NOW))
    n = 0
    for code, name, lc, hhmm, seal, to, ind, reason in ROWS:
        theme, main, sub, pt, score, sv = classify(code, ind, reason, lc)
        hh, mm = hhmm.split(":")
        first_t = f"{hh}{mm}00"
        ratio = round(seal / to, 3) if to else None
        seal_status = f"首封{hhmm} 封板{seal/1e8:.2f}亿"
        core = f"{reason}｜{theme}｜封板/成交比{ratio}" if ratio is not None else f"{reason}｜{theme}"
        tags = json.dumps({"main": main[:2], "sub": sub[:2], "main_zh": main, "sub_zh": sub,
                           "industry": ind, "theme": theme, "seal_amt_ratio": ratio,
                           "limit_count": lc, "afternoon_board": hhmm >= "13:00",
                           "source": "review_20260908"}, ensure_ascii=False)
        cur.execute("""insert into limit_up_patterns(trade_date,code,name,industry,board,limit_count,seal_status,first_limit_time,turnover,
                       primary_attribution,secondary_attribution,core_driver,predictability_score,feature_tags,pattern_type,
                       info_available_pre_open,strategy_value,created_at)
                       values(?,?,?,?,?,?,?,?,?,?,?,?,?,?,?,?,?,?)""",
                    (TRADE_DATE, code, name, ind, board_of(code), lc, seal_status, first_t, to,
                     main, sub, core, score, tags, pt, 0, sv, NOW))
        n += 1
    conn.commit()
    # 验收
    cur.execute("SELECT COUNT(*) FROM limit_up_patterns WHERE trade_date=? AND created_at=?", (TRADE_DATE, NOW))
    post = cur.fetchone()[0]
    cur.execute("SELECT pattern_type, COUNT(*) FROM limit_up_patterns WHERE trade_date=? AND created_at=? GROUP BY pattern_type", (TRADE_DATE, NOW))
    dist = cur.fetchall()
    cur.execute("SELECT code,name,industry,pattern_type,primary_attribution,predictability_score,seal_status FROM limit_up_patterns WHERE trade_date=? AND created_at=? LIMIT 5", (TRADE_DATE, NOW))
    sample = cur.fetchall()
    cur.execute("SELECT COUNT(*) FROM limit_up_patterns WHERE trade_date=? AND pattern_type='engine_v2'", (TRADE_DATE,))
    eng = cur.fetchone()[0]
    cur.execute("SELECT COUNT(*) FROM limit_up_patterns WHERE trade_date=?", (TRADE_DATE,))
    total_day = cur.fetchone()[0]
    conn.close()
    print(f"删除前本脚本行数={pre} 插入={n} 验收行数={post} (期望72)")
    print("pattern_type分布:", dist)
    print("engine_v2行数(应保持0):", eng, "| 当日总行数:", total_day)
    for s in sample: print("样本:", s)
    assert post == 72 and total_day == 72, f"行数异常 post={post} total={total_day}"
    print("OK")

if __name__ == "__main__":
    main()
